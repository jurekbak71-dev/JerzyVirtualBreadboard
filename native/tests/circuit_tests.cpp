#include "circuit.hpp"
#include <cmath>
#include <stdexcept>
#include <string>
#define CHECK(x) do { if(!(x)) throw std::runtime_error("failed: " #x); } while(false)
int main() {
 using namespace vbal;
 Circuit rc=makeRcCircuit(10000,1e-8,false);
 validateCircuit(rc);
 auto net=generateSpiceElements(rc);
 CHECK(net.find("R1 in out 10000")!=std::string::npos);
 CHECK(net.find("C1 out 0 1e-08")!=std::string::npos);
 CHECK(net.find("D1")==std::string::npos);
 Circuit clip=makeRcCircuit(10000,1e-8,true);
 auto diodes=generateSpiceElements(clip);
 CHECK(diodes.find("D1 out 0 DGEN")!=std::string::npos);
 CHECK(diodes.find("D2 0 out DGEN")!=std::string::npos);
 CHECK(diodes.find(".model DGEN D(")!=std::string::npos);
 auto exported=exportCircuitSpice(clip);
 CHECK(exported.find("Vin in 0 SIN(0 1 1000) AC 1")!=std::string::npos);
 CHECK(exported.find(".model DGEN")!=std::string::npos);
 auto bom=exportCircuitBomCsv(clip);
 CHECK(bom.find("Reference,Type,Value,Unit,Pin1,Pin2")!=std::string::npos);
 CHECK(bom.find("R1,Resistor,10000,ohm,in,out")!=std::string::npos);
 CHECK(bom.find("D2,SiliconDiode,,model:DGEN,0,out")!=std::string::npos);
 auto wiring=exportCircuitWiring(clip);
 CHECK(wiring.find("INPUT.signal")!=std::string::npos);
 CHECK(wiring.find("D1.1")!=std::string::npos);
 CHECK(wiring.find("OUTPUT.ground")!=std::string::npos);
 auto parsed=parseEditorSpiceElements(generateSpiceElements(clip));
 CHECK(parsed.parts.size()==4);
 CHECK(generateSpiceElements(parsed)==generateSpiceElements(clip));
 bool invalidDeck=false;
 try{parseEditorSpiceElements("R1 in out 10000\\nC1 out 0 1e-8\\n.control\\nquit\\n");}
 catch(const std::invalid_argument&){invalidDeck=true;}
 CHECK(invalidDeck);
 invalidDeck=false;
 try{parseEditorSpiceElements("R1 in out 10000\\nC1 out 0 1e-8\\n.save all\\n");}
 catch(const std::invalid_argument&){invalidDeck=true;}
 CHECK(invalidDeck);
 invalidDeck=false;
 try{parseEditorSpiceElements("R1 in out NaN\\nC1 out 0 1e-8\\n");}
 catch(const std::invalid_argument&){invalidDeck=true;}
 CHECK(invalidDeck);
 Circuit extended;
 extended.parts.push_back({"L1",PartType::Inductor,"in","out",0.01});
 extended.parts.push_back({"DLED1",PartType::Led,"out","0",0});
 validateCircuit(extended);
 auto extendedNet=generateSpiceElements(extended);
 CHECK(extendedNet.find("L1 in out 0.01")!=std::string::npos);
 CHECK(extendedNet.find("DLED1 out 0 LEDGEN")!=std::string::npos);
 CHECK(extendedNet.find(".model LEDGEN")!=std::string::npos);
 auto extendedParsed=parseEditorSpiceElements(extendedNet);
 CHECK(extendedParsed.parts.size()==2);
 CHECK(extendedParsed.parts[0].type==PartType::Inductor);
 CHECK(extendedParsed.parts[1].type==PartType::Led);
 auto extendedBom=exportCircuitBomCsv(extended);
 CHECK(extendedBom.find("L1,Inductor,0.01,H,in,out")!=std::string::npos);
 CHECK(extendedBom.find("DLED1,LED,,model:LEDGEN,out,0")!=std::string::npos);
 Circuit diodeSet;
 diodeSet.parts.push_back({"R1",PartType::Resistor,"in","out",1000.});
 diodeSet.parts.push_back({"DSCH1",PartType::SchottkyDiode,"out","n1",0.});
 diodeSet.parts.push_back({"DGE1",PartType::GermaniumDiode,"n1","n2",0.});
 diodeSet.parts.push_back({"DZ1",PartType::ZenerDiode,"n2","0",0.});
 validateCircuit(diodeSet);
 const auto diodeSetNet=generateSpiceElements(diodeSet);
 CHECK(diodeSetNet.find("DSCH1 out n1 SCHGEN")!=std::string::npos);
 CHECK(diodeSetNet.find("DGE1 n1 n2 GEGEN")!=std::string::npos);
 CHECK(diodeSetNet.find("DZ1 n2 0 Z5V1")!=std::string::npos);
 CHECK(diodeSetNet.find(".model SCHGEN")!=std::string::npos);
 CHECK(diodeSetNet.find(".model GEGEN")!=std::string::npos);
 CHECK(diodeSetNet.find(".model Z5V1")!=std::string::npos);
 const auto diodeSetParsed=parseEditorSpiceElements(diodeSetNet);
 CHECK(diodeSetParsed.parts[1].type==PartType::SchottkyDiode);
 CHECK(diodeSetParsed.parts[2].type==PartType::GermaniumDiode);
 CHECK(diodeSetParsed.parts[3].type==PartType::ZenerDiode);
 Circuit switched;
 switched.parts.push_back({"RSW1",PartType::Switch,"in","out",1.});
 switched.parts.push_back({"R1",PartType::Resistor,"out","0",1000.});
 validateCircuit(switched);
 const auto switchNet=generateSpiceElements(switched);
 CHECK(switchNet.find("RSW1 in out 0.01")!=std::string::npos);
 const auto switchParsed=parseEditorSpiceElements(switchNet);
 CHECK(switchParsed.parts[0].type==PartType::Switch);
 CHECK(switchParsed.parts[0].value==1.);
 switched.parts[0].value=0.;
 const auto openNet=generateSpiceElements(switched);
 CHECK(openNet.find("RSW1 in out 1000000000000")!=std::string::npos);
 CHECK(parseEditorSpiceElements(openNet).parts[0].value==0.);
 Circuit powered;
 powered.parts.push_back({"V1",PartType::DcVoltageSource,"vcc","0",9.});
 powered.parts.push_back({"R1",PartType::Resistor,"in","out",1000000.});
 powered.parts.push_back({"R2",PartType::Resistor,"vcc","out",1000.});
 powered.parts.push_back({"R3",PartType::Resistor,"out","0",1000.});
 validateCircuit(powered);
 const auto poweredNet=generateSpiceElements(powered);
 CHECK(poweredNet.find("V1 vcc 0 9")!=std::string::npos);
 const auto poweredParsed=parseEditorSpiceElements(poweredNet);
 CHECK(poweredParsed.parts[0].type==PartType::DcVoltageSource);
 CHECK(poweredParsed.parts[0].value==9.);
 Circuit npn;
 npn.parts.push_back({"V1",PartType::DcVoltageSource,"vcc","0",9.});
 npn.parts.push_back({"RIN",PartType::Resistor,"in","base",10000.});
 npn.parts.push_back({"RB",PartType::Resistor,"vcc","base",100000.});
 npn.parts.push_back({"RC",PartType::Resistor,"vcc","out",4700.});
 npn.parts.push_back({"Q1",PartType::NpnTransistor,"out","base",100.,"0"});
 validateCircuit(npn);
 const auto npnNet=generateSpiceElements(npn);
 CHECK(npnNet.find("Q1 out base 0 NPNGEN")!=std::string::npos);
 CHECK(npnNet.find(".model NPNGEN NPN(Is=1e-15 Bf=100 Vaf=100)")!=std::string::npos);
 const auto npnParsed=parseEditorSpiceElements(npnNet);
 CHECK(npnParsed.parts.back().type==PartType::NpnTransistor);
 CHECK(npnParsed.parts.back().pin3=="0");
 Circuit activeSet;
 activeSet.parts.push_back({"V1",PartType::DcVoltageSource,"vcc","0",9.});
 activeSet.parts.push_back({"R1",PartType::Resistor,"in","out",1000000.});
 activeSet.parts.push_back({"QP1",PartType::PnpTransistor,"out","in",100.,"vcc"});
 activeSet.parts.push_back({"M1",PartType::NmosTransistor,"out","in",2.0,"0"});
 activeSet.parts.push_back({"R2",PartType::Resistor,"out","0",1000.});
 validateCircuit(activeSet);
 const auto activeNet=generateSpiceElements(activeSet);
 CHECK(activeNet.find("QP1 out in vcc PNPGEN")!=std::string::npos);
 CHECK(activeNet.find("M1 out in 0 NMOSGEN")!=std::string::npos);
 CHECK(activeNet.find(".model PNPGEN PNP(")!=std::string::npos);
 CHECK(activeNet.find(".model NMOSGEN NMOS(")!=std::string::npos);
 const auto activeParsed=parseEditorSpiceElements(activeNet);
 CHECK(activeParsed.parts[2].type==PartType::PnpTransistor);
 CHECK(activeParsed.parts[3].type==PartType::NmosTransistor);
 Circuit jfet;
 jfet.parts.push_back({"V1",PartType::DcVoltageSource,"vcc","0",9.});
 jfet.parts.push_back({"RD",PartType::Resistor,"vcc","out",2200.});
 jfet.parts.push_back({"J1",PartType::NjfetTransistor,"out","in",2.0,"0"});
 validateCircuit(jfet);
 const auto jfetNet=generateSpiceElements(jfet);
 CHECK(jfetNet.find("J1 out in 0 NJFETGEN")!=std::string::npos);
 CHECK(jfetNet.find(".model NJFETGEN NJF(")!=std::string::npos);
 const auto jfetParsed=parseEditorSpiceElements(jfetNet);
 CHECK(jfetParsed.parts.back().type==PartType::NjfetTransistor);
 Circuit opamp;
 opamp.parts.push_back({"V1",PartType::DcVoltageSource,"vcc","0",5.});
 opamp.parts.push_back({"V2",PartType::DcVoltageSource,"vee","0",-5.});
 opamp.parts.push_back({"R1",PartType::Resistor,"out","fb",10000.});
 opamp.parts.push_back({"R2",PartType::Resistor,"fb","0",10000.});
 opamp.parts.push_back({"BOP1",PartType::OpAmp,"out","in",100000.,"fb","vcc","vee"});
 validateCircuit(opamp);
 const auto opampNet=generateSpiceElements(opamp);
 CHECK(opampNet.find("BOP1 out 0 V=max(V(vee)+0.2,min(V(vcc)-0.2,100000*(V(in)-V(fb))))")!=std::string::npos);
 const auto opampParsed=parseEditorSpiceElements(opampNet);
 CHECK(opampParsed.parts.back().type==PartType::OpAmp);
 CHECK(opampParsed.parts.back().pin4=="vcc");
 CHECK(opampParsed.parts.back().pin5=="vee");


 Circuit adjustedMos=activeSet;
 adjustedMos.parts[3].value=3.25;
 const auto adjustedMosDeck=generateSpiceElements(adjustedMos);
 CHECK(adjustedMosDeck.find("M1 out in 0 NMOS_M1")!=std::string::npos);
 CHECK(adjustedMosDeck.find(".model NMOS_M1 NMOS(VTO=3.25 KP=0.02 LAMBDA=0.02)")!=std::string::npos);
 const auto adjustedMosRoundtrip=parseEditorSpiceElements(adjustedMosDeck);
 CHECK(adjustedMosRoundtrip.parts[3].value==3.25);
 Circuit adjustedJfet=jfet;
 adjustedJfet.parts[2].value=1.4;
 const auto adjustedJfetDeck=generateSpiceElements(adjustedJfet);
 CHECK(adjustedJfetDeck.find("J1 out in 0 NJFET_J1")!=std::string::npos);
 CHECK(adjustedJfetDeck.find(".model NJFET_J1 NJF(BETA=0.002 VTO=-1.3999999999999999 LAMBDA=0.02)")!=std::string::npos
  ||adjustedJfetDeck.find(".model NJFET_J1 NJF(BETA=0.002 VTO=-1.4 LAMBDA=0.02)")!=std::string::npos);
 const auto adjustedJfetRoundtrip=parseEditorSpiceElements(adjustedJfetDeck);
 CHECK(std::abs(adjustedJfetRoundtrip.parts[2].value-1.4)<1e-12);
 Circuit namedModels;
 namedModels.parts.push_back({"V1",PartType::DcVoltageSource,"vneg","0",-9.});
 namedModels.parts.push_back({"R1",PartType::Resistor,"out","vneg",33000.});
 namedModels.parts.push_back({"C1",PartType::Capacitor,"in","out",2.2e-6});
 namedModels.parts.push_back({"Q1",PartType::PnpTransistor,"out","in",85.,"0"});
 namedModels.parts.back().germanium=true;
 validateCircuit(namedModels);
 const auto germaniumNet=generateSpiceElements(namedModels);
 CHECK(germaniumNet.find("Q1 out in 0 GPNP_Q1")!=std::string::npos);
 CHECK(germaniumNet.find(".model GPNP_Q1 PNP(Is=5e-6 Bf=85 Vaf=40 Eg=0.72)")!=std::string::npos);
 const auto germaniumParsed=parseEditorSpiceElements(germaniumNet);
 CHECK(germaniumParsed.parts.back().germanium);
 CHECK(germaniumParsed.parts.back().value==85.);
 CHECK(germaniumParsed.parts[0].value==-9.);
 Circuit transistorBeta=namedModels;
 transistorBeta.parts.back().germanium=false;
 transistorBeta.parts.back().value=120.;
 const auto siliconBetaNet=generateSpiceElements(transistorBeta);
 CHECK(siliconBetaNet.find(".model PNP_Q1 PNP(Is=1e-15 Bf=120 Vaf=100)")!=std::string::npos);
 const auto siliconParsed=parseEditorSpiceElements(siliconBetaNet);
 CHECK(!siliconParsed.parts.back().germanium);
 CHECK(siliconParsed.parts.back().value==120.);

 Circuit mixed;
 mixed.parts.push_back({"V1",PartType::DcVoltageSource,"vcc","0",5.});
 mixed.parts.push_back({"R1",PartType::Resistor,"in","sig",1000.});
 mixed.parts.push_back({"R2",PartType::Resistor,"vco","0",2000.});
 mixed.parts.push_back({"R3",PartType::Resistor,"out","0",100000.});
 mixed.parts.push_back({"C1",PartType::Capacitor,"wet","out",1e-6});
 Part ic{"X1",PartType::Pt2399,"vcc","ref",0.,"0","0","clk"};
 ic.extraPins={"vco","cc1","cc0","op1out","op1in","op2in","op2out","lpf2in","wet","lpf1out","sig"};
 mixed.parts.push_back(ic);
 validateCircuit(mixed);
 const auto deck=generateSpiceElements(mixed);
 CHECK(deck.find("X1 vcc ref 0 0 clk vco cc1 cc0 op1out op1in op2in op2out lpf2in wet lpf1out sig PT2399_VBAL")!=std::string::npos);
 const auto parsedMixed=parseEditorSpiceElements(deck);
 CHECK(parsedMixed.parts.back().type==PartType::Pt2399);
 CHECK(parsedMixed.parts.back().extraPins.size()==11);
 CHECK(generateSpiceElements(parsedMixed)==deck);
 bool rejectsSpice=false;
 try{(void)exportCircuitSpice(mixed);}catch(const std::invalid_argument&){rejectsSpice=true;}
 CHECK(rejectsSpice);

 Circuit bbdNet;
 bbdNet.parts.push_back({"V1",PartType::DcVoltageSource,"vneg","0",-15.});
 bbdNet.parts.push_back({"R1",PartType::Resistor,"in","signal",4700.});
 bbdNet.parts.push_back({"R2",PartType::Resistor,"signal","0",100000.});
 bbdNet.parts.push_back({"R3",PartType::Resistor,"osc","0",22000.});
 bbdNet.parts.push_back({"C1",PartType::Capacitor,"oscCap","0",100e-12});
 bbdNet.parts.push_back({"C2",PartType::Capacitor,"bbdOut","out",1e-6});
 bbdNet.parts.push_back({"R4",PartType::Resistor,"out","0",100000.});
 Part clock{"XCLK1",PartType::Mn3101,"0","cp1",0.,"vneg","cp2","oscCap"};
 clock.extraPins={"osc","oscIn","vgg"};
 bbdNet.parts.push_back(clock);
 Part buckets{"XBB1",PartType::Mn3007,"0","cp1",0.,"signal","vgg","vneg"};
 buckets.extraPins={"cp2","bbdOut","bbdOut2"};
 bbdNet.parts.push_back(buckets);
 validateCircuit(bbdNet);
 const auto bbdText=generateSpiceElements(bbdNet);
 CHECK(bbdText.find("XCLK1 0 cp1 vneg cp2 oscCap osc oscIn vgg MN3101_VBAL")!=std::string::npos);
 CHECK(bbdText.find("XBB1 0 cp1 signal vgg vneg cp2 bbdOut bbdOut2 MN3007_VBAL")!=std::string::npos);
 const auto parsedBbd=parseEditorSpiceElements(bbdText);
 CHECK(parsedBbd.parts.back().type==PartType::Mn3007);
 CHECK(parsedBbd.parts[parsedBbd.parts.size()-2].type==PartType::Mn3101);
 CHECK(generateSpiceElements(parsedBbd)==bbdText);
 auto rejected=[](Circuit c){try{validateCircuit(c);return false;}catch(const std::invalid_argument&){return true;}};
 auto duplicate=rc;duplicate.parts[1].reference="R1";CHECK(rejected(duplicate));
 auto shorted=rc;shorted.parts[0].pin2="in";CHECK(rejected(shorted));
 auto badValue=rc;badValue.parts[0].value=-10;CHECK(rejected(badValue));
 auto badNode=rc;badNode.parts[0].pin1="in;quit";CHECK(rejected(badNode));
 auto floating=rc;floating.parts[1].pin2="floating";CHECK(rejected(floating));
 auto missingOutput=rc;missingOutput.outputNode="missing";CHECK(rejected(missingOutput));
}
