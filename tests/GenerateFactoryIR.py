#!/usr/bin/env python3
"""Generate five original deterministic, synthetic mono impulse responses (CC0-1.0).

No real room recordings or sampled third-party content. Pure Python stdlib.
The generated C++ header contains only nonzero PCM16 taps (lossless relative to
its WAV outputs), allowing the plugin to reconstruct the exact sampled kernels.
"""
from __future__ import annotations
from dataclasses import dataclass
from pathlib import Path
import argparse
import hashlib
import math
import struct
import sys
import tempfile
import wave

SAMPLE_RATE = 48000
SPEED_OF_SOUND = 343.0
SCALE = 32768.0

@dataclass(frozen=True)
class RoomSpec:
    name: str
    symbol: str
    dimensions: tuple[float, float, float] | None
    seconds: float
    t60: float
    pre_delay: float
    density_per_second: int
    wall_reflectivity: float
    seed: int
    profile: str

ROOMS = (
    RoomSpec('Booth', 'Booth', (1.8, 1.6, 2.25), 0.45, 0.20, .002, 800, .38, 0xB007, 'room'),
    RoomSpec('Small Room', 'SmallRoom', (4.2, 3.3, 2.6), 0.90, 0.42, .008, 1400, .57, 0x5A11, 'room'),
    RoomSpec('Studio', 'Studio', (7.4, 5.7, 3.4), 1.45, 0.74, .013, 2100, .66, 0x57D0, 'room'),
    RoomSpec('Plate', 'Plate', None, 2.30, 1.48, .004, 4600, .79, 0xA71E, 'plate'),
    RoomSpec('Hall', 'Hall', (24.0, 15.5, 10.4), 3.70, 2.40, .034, 3400, .81, 0x4A11, 'room'),
)

def rng_next(state: int) -> int:
    state ^= (state << 13) & 0xFFFFFFFF
    state ^= state >> 17
    state ^= (state << 5) & 0xFFFFFFFF
    return state & 0xFFFFFFFF

def add_early_reflections(signal: list[float], spec: RoomSpec) -> None:
    if spec.profile == 'plate':
        # Tapped, incommensurate metal-plate modes; this is a synthetic plate,
        # not a claim of a physical plate transfer-function measurement.
        for mode in range(1, 56):
            time = .004 + .0017 * mode + .000024 * mode * mode
            sample = int(round(time * SAMPLE_RATE))
            if sample >= len(signal):
                break
            level = (.62 ** (mode / 5)) * (.19 if mode % 2 else -.16)
            signal[sample] += level
        return
    assert spec.dimensions is not None
    width, depth, height = spec.dimensions
    source = (width * .31, depth * .43, height * .55)
    microphone = (width * .67, depth * .61, height * .48)
    # Image-source approximation for low-order axial wall reflections.
    # Deliberately not described as a calibrated real acoustic measurement.
    for axis in range(3):
        for n in (-3, -2, -1, 1, 2, 3):
            mirrored = list(source)
            mirrored[axis] = 2.0 * n * spec.dimensions[axis] + (-source[axis] if n & 1 else source[axis])
            distance = math.sqrt(sum((mirrored[k] - microphone[k]) ** 2 for k in range(3)))
            delay = int(round((spec.pre_delay + distance / SPEED_OF_SOUND) * SAMPLE_RATE))
            if delay >= len(signal):
                continue
            level = (spec.wall_reflectivity ** abs(n)) / (1.0 + distance)
            if (axis + n) % 3 == 0:
                level = -level
            signal[delay] += level * .48

def synthesize(spec: RoomSpec) -> tuple[int, ...]:
    count = int(round(spec.seconds * SAMPLE_RATE))
    values = [0.0] * count
    # Direct path is deliberately below full-scale to preserve early reflections.
    values[0] = .42 if spec.profile == 'plate' else .56
    add_early_reflections(values, spec)
    state = spec.seed
    start = max(1, round(spec.pre_delay * SAMPLE_RATE))
    density = int(spec.density_per_second * spec.seconds)
    for _ in range(density):
        state = rng_next(state)
        position = start + state % (count - start)
        state = rng_next(state)
        amplitude = ((state & 0xFFFF) / 32767.5) - 1.0
        state = rng_next(state)
        amplitude *= .45 + .55 * (state & 0xFFFF) / 65535.0
        moment = position / SAMPLE_RATE
        tail = math.exp(-math.log(1000.0) * moment / spec.t60)
        strength = (.073 if spec.profile == 'plate' else .052) * math.sqrt(1000.0 / spec.density_per_second)
        # Hall decorrelates the late tail from its prominent predelay.
        if spec.profile == 'room' and spec.name == 'Hall':
            strength *= 1.12
        values[position] += amplitude * tail * strength
    maximum = max(abs(value) for value in values)
    assert maximum > 0
    gain = 24576.0 / maximum
    return tuple(max(-32768, min(32767, int(round(x * gain)))) for x in values)

def wave_bytes(pcm: tuple[int, ...]) -> bytes:
    import io
    buf = io.BytesIO()
    with wave.open(buf, 'wb') as wav:
        wav.setnchannels(1)
        wav.setsampwidth(2)
        wav.setframerate(SAMPLE_RATE)
        wav.writeframes(struct.pack('<' + 'h' * len(pcm), *pcm))
    return buf.getvalue()

def header_text(kernels: tuple[tuple[int, ...], ...]) -> str:
    rows = [
        '#pragma once',
        '// GENERATED by tests/GenerateFactoryIR.py; do not edit by hand.',
        '// All IRs are original synthetic signals, dedicated CC0-1.0. NOT recordings.',
        '#include <juce_audio_basics/juce_audio_basics.h>',
        '#include <array>', '#include <cstddef>', '#include <cstdint>',
        'namespace JerzyFactoryIR {',
        'struct Tap {std::uint32_t position;std::int16_t amplitude;};',
        'struct Kernel {const char* name;const Tap* taps;std::size_t count;int frames;};',
        'inline constexpr int sampleRate = 48000;',
        'inline constexpr int count = 5;',
    ]
    for spec, kernel in zip(ROOMS, kernels):
        rows.append(f'inline constexpr Tap k{spec.symbol}[] = {{')
        taps = [(i, x) for i, x in enumerate(kernel) if x]
        for base in range(0, len(taps), 7):
            rows.append(' ' + ', '.join('{{{}, {}}}'.format(index, value) for index, value in taps[base:base+7]) + ',')
        rows.append('};')
    rows.append('inline constexpr std::array<Kernel, 5> kernels = {{')
    for spec, kernel in zip(ROOMS, kernels):
        rows.append(f' {{"{spec.name}", k{spec.symbol}, sizeof(k{spec.symbol}) / sizeof(Tap), {len(kernel)}}},')
    rows.extend([
        '}};',
        'inline const char* nameFor(int requested) noexcept {',
        ' return kernels[static_cast<std::size_t>(requested >= 0 && requested < count ? requested : 0)].name;',
        '}',
        'inline juce::AudioBuffer<float> makeSyntheticFactoryRoom(int requested) {',
        ' const auto& k = kernels[static_cast<std::size_t>(requested >= 0 && requested < count ? requested : 0)];',
        ' juce::AudioBuffer<float> result(1, k.frames);',
        ' result.clear();',
        ' for (std::size_t i = 0; i < k.count; ++i)',
        '   result.setSample(0, static_cast<int>(k.taps[i].position), static_cast<float>(k.taps[i].amplitude) / 32768.0f);',
        ' return result;',
        '}',
        '} // namespace JerzyFactoryIR',
        '',
    ])
    return '\n'.join(rows)

def generated_files() -> dict[str, bytes]:
    pcm = tuple(synthesize(spec) for spec in ROOMS)
    outputs = {'Source/FactoryRooms.h': header_text(pcm).encode('utf-8')}
    for spec, kernel in zip(ROOMS, pcm):
        outputs['assets/ir/' + spec.symbol + '.wav'] = wave_bytes(kernel)
    return outputs

def write_or_check(root: Path, *, check: bool) -> bool:
    outputs = generated_files()
    ok = True
    for name, content in outputs.items():
        target = root / name
        digest = hashlib.sha256(content).hexdigest()
        if check:
            if not target.is_file() or target.read_bytes() != content:
                print('MISMATCH:', name, file=sys.stderr)
                ok = False
            else:
                print('OK:', name, len(content), digest)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
            print('WRITTEN:', name, len(content), digest)
    return ok

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parent.parent,
                        help='Repository root, containing Source/ and assets/')
    parser.add_argument('--check', action='store_true', help='Byte-for-byte reproducibility check')
    args = parser.parse_args()
    return 0 if write_or_check(args.root, check=args.check) else 1

if __name__ == '__main__':
    sys.exit(main())
