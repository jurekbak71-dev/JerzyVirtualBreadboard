#!/usr/bin/env python3
"""Original synthetic image-source approximation, dedicated to CC0-1.0.
Room 6x4x2.8m, source (1.4,1.2,1.1)m, mic (3.2,2.3,1.4)m.
343m/s sound speed; reflection amplitude0.72 per wall encounter.
Image orders -6..6 per axis; inverse-distance propagation; no diffusion,
frequency-dependent absorption or measurement claims. 48kHz mono24bit.
"""
import math, wave, pathlib
root=pathlib.Path(__file__).resolve().parents[1]
rate=48000; room=(6.,4.,2.8); source=(1.4,1.2,1.1); mic=(3.2,2.3,1.4)
taps={}
for ix in range(-6,7):
 for iy in range(-6,7):
  for iz in range(-6,7):
   indices=(ix,iy,iz)
   image=[n*d+(s if n%2==0 else d-s) for n,d,s in zip(indices,room,source)]
   distance=math.sqrt(sum((a-b)**2 for a,b in zip(image,mic)))
   sample=round(distance/343*rate)
   amplitude=.72**sum(abs(n) for n in indices)/max(distance,.1)
   taps[sample]=taps.get(sample,0)+amplitude
length=max(taps)+1; normal=sum(abs(a) for a in taps.values())
quantized={i:round(a/normal*.95*8388607) for i,a in taps.items()}
with wave.open(str(root/'assets/ir/synthetic-small-room.wav'),'wb') as w:
 w.setnchannels(1);w.setsampwidth(3);w.setframerate(rate)
 w.writeframes(b''.join(quantized.get(i,0).to_bytes(3,'little',signed=True) for i in range(length)))
header='''#pragma once
#include <juce_audio_basics/juce_audio_basics.h>
// Generated by tests/GenerateFactoryIR.py. Original synthetic room, CC0-1.0.
inline juce::AudioBuffer<float> makeSyntheticFactoryRoom() {
 struct Tap {int sample;float value;};
 static constexpr Tap taps[]={\n'''
header+=''.join(f' {{{i},{v/8388607:.10g}f}},\n' for i,v in sorted(quantized.items()))
header+=' };\n juce::AudioBuffer<float> room(1,'+str(length)+');room.clear();for(const auto& tap:taps)room.setSample(0,tap.sample,tap.value);return room;\n}\n'
(root/'Source/FactoryRoom.h').write_text(header)
print(f'{length} samples, {length/rate:.4f}s, {len(taps)} taps')
